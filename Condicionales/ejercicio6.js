let palabra = "perro";

if (palabra === "casa") {
    console.log("house");
} else if (palabra === "perro") {
    console.log("dog");
} else if (palabra === "pelota") {
    console.log("ball");
} else if (palabra === "árbol" || palabra === "arbol") {
    console.log("tree");
} else if (palabra === "genio") {
    console.log("genius");
} else {
    console.log("La palabra ingresada es incorrecta.");
}